/**
 * Filter locations by district name or state name
 */
export function searchIndiaLocations(query: string, stateFilter?: string): IndiaLocation[] {
  const cleanQ = query.trim().toLowerCase();
  
  return INDIA_DISTRICTS.filter((loc) => {
    const matchesStateFilter = !stateFilter || stateFilter === 'ALL' || loc.state.toLowerCase() === stateFilter.toLowerCase();
    if (!matchesStateFilter) return false;

    if (!cleanQ) return true;
    
    return (
      loc.name.toLowerCase().includes(cleanQ) ||
      loc.state.toLowerCase().includes(cleanQ)
    );
  });
}
